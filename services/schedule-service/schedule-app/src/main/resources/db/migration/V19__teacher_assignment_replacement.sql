CREATE OR REPLACE FUNCTION guard_pending_replacement_assignment_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    operation_id_value UUID;
BEGIN
    operation_id_value := NULLIF(current_setting(
        'rutcampustrack.schedule_assignment_rebind_operation_id', true), '')::UUID;
    IF EXISTS (
        SELECT 1
          FROM schedule_assignment_replacement_operations
         WHERE target_assignment_id = NEW.assignment_id
           AND state <> 'COMMITTED'
           AND (operation_id IS DISTINCT FROM operation_id_value OR state <> 'APPLIED')
    ) THEN
        RAISE EXCEPTION 'target assignment is fenced until replacement schedule commit';
    END IF;
    RETURN NEW;
END
$$;

