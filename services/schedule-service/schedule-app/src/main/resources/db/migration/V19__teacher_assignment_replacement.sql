CREATE OR REPLACE FUNCTION validate_schedule_assignment_replacement_template_insert()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    operation_state_value VARCHAR(16);
    source_active_value BOOLEAN;
    target_active_value BOOLEAN;
BEGIN
    SELECT state INTO operation_state_value
      FROM schedule_assignment_replacement_operations
     WHERE operation_id = NEW.operation_id
     FOR UPDATE;
    IF NOT FOUND OR operation_state_value <> 'APPLIED' THEN
        RAISE EXCEPTION 'replacement templates are cloned only during the confirmed apply phase';
    END IF;
    SELECT is_active INTO source_active_value
      FROM schedule_items
     WHERE id = NEW.source_schedule_item_id
     FOR UPDATE;
    IF NOT FOUND OR source_active_value IS DISTINCT FROM NEW.source_was_active THEN
        RAISE EXCEPTION 'replacement template active state differs from its source';
    END IF;
    SELECT is_active INTO target_active_value
      FROM schedule_items
     WHERE id = NEW.target_schedule_item_id
     FOR UPDATE;
    IF NOT FOUND OR target_active_value THEN
        RAISE EXCEPTION 'replacement target template must remain inactive until commit';
    END IF;
    RETURN NEW;
END
$$;

