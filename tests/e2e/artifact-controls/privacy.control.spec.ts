test('only the canonical dedicated reporter passes before credential creation', async ({}, info) => {
  const baseline: WorkerInfo = {
    config: info.config,
    project: info.project,
    parallelIndex: info.parallelIndex,
    workerIndex: info.workerIndex,
  };
  const accepts = (candidate: WorkerInfo) => {
    try {
      requirePrivateArtifacts(candidate);
      return true;
    } catch {
      return false;
    }
  };
  const alternateDir = mkdtempSync(join(tmpdir(), 'rct-reporter-identity-'));
  try {
    const alternatePath = join(alternateDir, 'safe-reporter.ts');
    writeFileSync(alternatePath, 'export default class AlternateReporter {}');
    const controls = {
      canonicalReporterAccepted: accepts(baseline),
      sameBasenameAlternateRejected: !accepts({
        ...baseline,
        config: { ...baseline.config, reporter: [[require.resolve(alternatePath)]] },
      }),
      extraReporterRejected: !accepts({
        ...baseline,
        config: { ...baseline.config, reporter: [...baseline.config.reporter, ['html']] },
      }),
      traceRejected: !accepts({
        ...baseline,
        project: { ...baseline.project, use: { ...baseline.project.use, trace: 'on' } },
      }),
      videoRejected: !accepts({
        ...baseline,
        project: { ...baseline.project, use: { ...baseline.project.use, video: 'on' } },
      }),
      screenshotRejected: !accepts({
        ...baseline,
        project: { ...baseline.project, use: { ...baseline.project.use, screenshot: 'on' } },
      }),
      missingSnapshotGuardRejected: false,
      wrongSnapshotGuardRejected: false,
    };
    const snapshotGuard = process.env.PLAYWRIGHT_NO_COPY_PROMPT;
    try {
      delete process.env.PLAYWRIGHT_NO_COPY_PROMPT;
      controls.missingSnapshotGuardRejected = !accepts(baseline);
      process.env.PLAYWRIGHT_NO_COPY_PROMPT = '0';
      controls.wrongSnapshotGuardRejected = !accepts(baseline);
    } finally {
      process.env.PLAYWRIGHT_NO_COPY_PROMPT = snapshotGuard;
    }
    writeFileSync(info.outputPath('guard-control.json'), JSON.stringify(controls));
    expect(controls.canonicalReporterAccepted).toBe(true);
    expect(controls.sameBasenameAlternateRejected).toBe(true);
    expect(controls.extraReporterRejected).toBe(true);
    expect(controls.traceRejected).toBe(true);
    expect(controls.videoRejected).toBe(true);
    expect(controls.screenshotRejected).toBe(true);
    expect(controls.missingSnapshotGuardRejected).toBe(true);
    expect(controls.wrongSnapshotGuardRejected).toBe(true);
  } finally {
    rmSync(alternateDir, { recursive: true, force: true });
  }
});
