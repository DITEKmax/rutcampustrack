test('successful sensitive step metadata and worker output are not emitted', async ({}, info) => {
  for (const status of [200, 201, 202, 400, 401, 403, 404, 409, 503]) {
    const failure = datasetHttpFailure('POST', '/api/academic/users/123/archive', status);
    const diagnostic = classifySafeFailure(failure);
    expect(diagnostic).toEqual({
      stage: 'DATASET_HTTP',
      cause: 'DATASET_USER_ARCHIVE_HTTP',
      httpStatus: status,
    });
    expect(
      safeFailureDiagnostics([
        { type: safeFailureAnnotation, description: `DATASET_USER_ARCHIVE_HTTP:${status}` },
      ]),
    ).toEqual([diagnostic]);
    expect(failure.message.includes('/api/')).toBe(false);
    expect(failure.message.includes('123')).toBe(false);
  }
  for (const [method, path, status] of [
    ['GET', '/api/academic/users/123/archive', 403],
    ['POST', '/api/academic/users/123/archive-preview', 409],
    ['POST', `/api/academic/users/123/archive?${marker}`, 503],
    ['POST', '/api/academic/users/123/archive', 204],
    ['POST', '/api/academic/users/123/archive', 302],
    ['POST', '/api/academic/users/123/archive', 999],
    ['POST', '/api/academic/users/123/archive', marker],
  ]) {
    const failure = datasetHttpFailure(method, path, status);
    expect(classifySafeFailure(failure)).toEqual({
      stage: 'UNKNOWN',
      cause: 'UNKNOWN',
      httpStatus: 0,
    });
    expect(failure.message.includes(marker)).toBe(false);
    expect(failure.message.includes('/api/')).toBe(false);
  }
  const rosterReasons = [
    ['Пара ещё не началась', 'NOT_STARTED'],
    ['Отсутствует право изменять отметку', 'PERMISSION_DENIED'],
    ['Семестр архивирован', 'SEMESTER_ARCHIVED'],
    ['Изменения в семестре заблокированы', 'SEMESTER_WRITE_BLOCKED'],
    ['Перенос пары ещё не завершён', 'TRANSFER_PENDING'],
    ['Пара отменена', 'LESSON_CANCELLED'],
  ];
  for (const [editBlockedReason, reportedEditBlock] of rosterReasons) {
    const facts = rosterEditBlockFacts({ editBlockedReason });
    expect(facts).toEqual({ blockedReasonPresent: true, reportedEditBlock });
    validateFacts(facts);
  }
  for (const target of [undefined, {}, { editBlockedReason: null }, { editBlockedReason: '' }]) {
    expect(rosterEditBlockFacts(target)).toEqual({
      blockedReasonPresent: false,
      reportedEditBlock: 'NONE',
    });
  }
  // The obsolete field cannot supply a reason; arbitrary server content emits only UNKNOWN.
  expect(rosterEditBlockFacts({ blockedReason: 'Пара ещё не началась' })).toEqual({
    blockedReasonPresent: false,
    reportedEditBlock: 'NONE',
  });
  for (const editBlockedReason of ['unrecognized', {}, 42]) {
    const facts = rosterEditBlockFacts({ editBlockedReason });
    expect(facts).toEqual({ blockedReasonPresent: true, reportedEditBlock: 'UNKNOWN' });
    validateFacts(facts);
  }
  expect(() => validateFacts({ reportedEditBlock: 'unrecognized' })).toThrow();

  const title = renderTitleForCall({ type: 'Frame', method: 'fill', params: { value: marker } });
  expect(title.includes(marker)).toBe(true); // reproduces the pinned library's original leak
  await test.step(title, async () => {
    console.log(marker);
    console.error(marker);
  });
  writeFileSync(
    info.outputPath('control.json'),
    JSON.stringify({ originalFillTitleContainsMarker: true }),
  );

  const spec = resolve(__dirname, '../specs/mobile-real-server.spec.ts');
  const fallback = { file: spec, line: 61, column: 1 };
  const frame = (line = 91, column = 1) => `    at (${spec}:${line}:${column})`;
  const sanitize = (error: Record<string, unknown>) => {
    const reported = {
      file: spec,
      line: 61,
      status: 'failed',
      errors: [error],
      annotations: [],
    } as unknown as TestInfo;
    sanitizeTestErrors(reported);
    expect(reported.status).toBe('failed');
    expect(reported.errors.length).toBe(1);
    expect(JSON.stringify(error).includes(marker)).toBe(false);
    return reported;
  };
  const projected: Record<string, unknown> = {
    message: marker,
    stack: `Error: ${marker}\nprivate assertion details\n${frame()}\n${frame(102)}`,
    location: fallback,
  };
  const reported = sanitize(projected);
  expect(projected.location).toEqual({ file: spec, line: 91, column: 1 });
  const firstPass = JSON.stringify(projected);
  sanitizeTestErrors(reported);
  expect(JSON.stringify(projected)).toBe(firstPass);
  // The exact fabricated frame is deliberately accepted only as an untrusted reported hint.
  expect(reported.status).toBe('failed');

  const named: Record<string, unknown> = { stack: `Error\n    at async body (${spec}:102:1)` };
  sanitize(named);
  expect(named.location).toEqual({ file: spec, line: 102, column: 1 });
  const bare: Record<string, unknown> = { stack: `Error\n    at ${spec}:91:1` };
  sanitize(bare);
  expect(bare.location).toEqual({ file: spec, line: 91, column: 1 });

  for (const stack of [
    `Error\n    at (/private/${marker}.ts:91:1)`,
    `Error\n    at (file://${spec}:91:1)`,
    `Error\n    at (${spec}/../mobile-real-server.spec.ts:91:1)`,
    `Error\n    at (${spec}:0:1)`,
    `Error\n    at (${spec}:989:1)`,
    `Error\n    at (${spec}:91:999999)`,
    `Error\n    at (${spec}:91:0)`,
    `Error\n${frame()}\u0000`,
    `Error\n${frame()}\u001b`,
    `Error\n${frame()}\r`,
    `Error\n${frame()}\u2028`,
    `Error\n    at (${spec}:91:1`,
    `Error\n    at unexpected frame\n${frame()}`,
    `${'x'.repeat(8193)}\n${frame()}`,
    `${'header\n'.repeat(64)}${frame()}`,
    `Error\n    at ${'x'.repeat(1025)}\n${frame()}`,
    42,
    null,
  ]) {
    const refused: Record<string, unknown> = {
      stack,
      location: { file: `/private/${marker}.ts`, line: 987, column: 1 },
    };
    sanitize(refused);
    expect(refused.location).toEqual(fallback);
  }

  let getterCalls = 0;
  const getters: Record<string, unknown> = { stack: `Error\n${frame()}` };
  for (const key of ['message', 'location', 'name', 'toString']) {
    Object.defineProperty(getters, key, {
      enumerable: true,
      configurable: true,
      get() {
        getterCalls++;
        throw new Error(marker);
      },
    });
  }
  sanitize(getters);
  expect(getters.location).toEqual({ file: spec, line: 91, column: 1 });
  const inherited = Object.create({
    get stack() {
      getterCalls++;
      return frame();
    },
  });
  sanitize(inherited);
  expect(inherited.location).toEqual(fallback);
  const stackGetter: Record<string, unknown> = {};
  Object.defineProperty(stackGetter, 'stack', {
    enumerable: true,
    configurable: true,
    get() {
      getterCalls++;
      return frame();
    },
  });
  sanitize(stackGetter);
  expect(stackGetter.location).toEqual(fallback);
  expect(getterCalls).toBe(0);
});

