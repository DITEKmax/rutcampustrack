-- Teacher replacement is the only workflow allowed to rebind an existing
-- recurring occurrence.  A fence keeps its retained-row boundary separate
-- from the boundary for creating new occurrences.

ALTER TABLE schedule_assignment_fences
    ADD COLUMN creation_cap_until_exclusive DATE;

UPDATE schedule_assignment_fences
   SET creation_cap_until_exclusive = cap_until_exclusive;

ALTER TABLE schedule_assignment_fences
    ALTER COLUMN creation_cap_until_exclusive SET NOT NULL,
    DROP CONSTRAINT schedule_assignment_fences_interval_chk,
    ADD CONSTRAINT schedule_assignment_fences_retention_interval_chk
        CHECK (cap_until_exclusive >= valid_from),
    ADD CONSTRAINT schedule_assignment_fences_creation_interval_chk
        CHECK (creation_cap_until_exclusive >= valid_from
               AND creation_cap_until_exclusive <= cap_until_exclusive);

CREATE TABLE schedule_assignment_replacement_operations
(
    operation_id         UUID PRIMARY KEY,
    payload_hash         BYTEA       NOT NULL,
    source_assignment_id BIGINT      NOT NULL,
    target_assignment_id BIGINT      NOT NULL,
    source_teacher_id    BIGINT      NOT NULL,
    target_teacher_id    BIGINT      NOT NULL,
    group_id             BIGINT      NOT NULL,
    subject_id           BIGINT      NOT NULL,
    semester_id          BIGINT      NOT NULL,
    lesson_type          VARCHAR(16) NOT NULL,
    source_valid_from    DATE        NOT NULL,
    valid_until_exclusive DATE       NOT NULL,
    effective_from       DATE        NOT NULL,
    state                VARCHAR(16) NOT NULL,
    moved_count          BIGINT      NOT NULL DEFAULT 0,
    skipped_count        BIGINT      NOT NULL DEFAULT 0,
    created_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at           TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT schedule_assignment_replacement_hash_chk CHECK (octet_length(payload_hash) = 32),
    CONSTRAINT schedule_assignment_replacement_source_chk CHECK (source_assignment_id > 0),
    CONSTRAINT schedule_assignment_replacement_target_chk CHECK (target_assignment_id > 0),
    CONSTRAINT schedule_assignment_replacement_teachers_chk
        CHECK (source_teacher_id > 0 AND target_teacher_id > 0 AND source_teacher_id <> target_teacher_id),
    CONSTRAINT schedule_assignment_replacement_scope_chk
        CHECK (group_id > 0 AND subject_id > 0 AND semester_id > 0
               AND lesson_type IN ('lecture', 'practice', 'lab')),
    CONSTRAINT schedule_assignment_replacement_interval_chk
        CHECK (source_valid_from <= effective_from
               AND effective_from <= valid_until_exclusive
               AND valid_until_exclusive > effective_from),
    CONSTRAINT schedule_assignment_replacement_state_chk
        CHECK (state IN ('PREPARED', 'APPLIED', 'COMMITTED')),
    CONSTRAINT schedule_assignment_replacement_counts_chk
        CHECK (moved_count >= 0 AND skipped_count >= 0),
    CONSTRAINT schedule_assignment_replacement_pair_chk
        CHECK (source_assignment_id <> target_assignment_id)
);

CREATE TABLE schedule_assignment_replacement_templates
(
    operation_id              UUID   NOT NULL
        REFERENCES schedule_assignment_replacement_operations (operation_id) ON DELETE RESTRICT,
    source_schedule_item_id   BIGINT NOT NULL
        REFERENCES schedule_items (id) ON DELETE RESTRICT,
    target_schedule_item_id   BIGINT NOT NULL UNIQUE
        REFERENCES schedule_items (id) ON DELETE RESTRICT,
    source_was_active          BOOLEAN NOT NULL,
    created_at                TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    PRIMARY KEY (operation_id, source_schedule_item_id),
    CONSTRAINT schedule_assignment_replacement_template_distinct_chk
        CHECK (source_schedule_item_id <> target_schedule_item_id)
);

CREATE TABLE schedule_assignment_rebind_ledger
(
    ledger_id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    operation_id                 UUID        NOT NULL
        REFERENCES schedule_assignment_replacement_operations (operation_id) ON DELETE RESTRICT,
    source_schedule_item_id      BIGINT      NOT NULL
        REFERENCES schedule_items (id) ON DELETE RESTRICT,
    target_schedule_item_id      BIGINT      NOT NULL
        REFERENCES schedule_items (id) ON DELETE RESTRICT,
    occurrence_id                BIGINT      NOT NULL
        REFERENCES lesson_occurrences (id) ON DELETE RESTRICT,
    lesson_id                    BIGINT
        REFERENCES lessons (id) ON DELETE RESTRICT,
    occurrence_date              DATE        NOT NULL,
    expected_occurrence_revision BIGINT      NOT NULL,
    after_occurrence_revision    BIGINT      NOT NULL,
    expected_lesson_revision     BIGINT,
    after_lesson_revision        BIGINT,
    before_schedule_item_id      BIGINT      NOT NULL,
    after_schedule_item_id       BIGINT      NOT NULL,
    before_assignment_id         BIGINT      NOT NULL,
    after_assignment_id          BIGINT      NOT NULL,
    before_teacher_id            BIGINT      NOT NULL,
    after_teacher_id             BIGINT      NOT NULL,
    result                       VARCHAR(40) NOT NULL,
    created_at                   TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT schedule_assignment_rebind_revision_chk
        CHECK (expected_occurrence_revision > 0
               AND after_occurrence_revision >= expected_occurrence_revision
               AND (expected_lesson_revision IS NULL OR expected_lesson_revision > 0)
               AND (after_lesson_revision IS NULL OR after_lesson_revision >= expected_lesson_revision)),
    CONSTRAINT schedule_assignment_rebind_result_chk CHECK (result IN (
        'MOVED', 'SKIPPED_CANCELLED', 'SKIPPED_ACTIVE', 'SKIPPED_CLOSED',
        'SKIPPED_ALREADY_STARTED', 'SKIPPED_NO_CURRENT_LESSON')),
    CONSTRAINT schedule_assignment_rebind_date_uq
        UNIQUE (operation_id, source_schedule_item_id, occurrence_date)
);

CREATE INDEX idx_schedule_assignment_rebind_target_date
    ON schedule_assignment_rebind_ledger (after_assignment_id, occurrence_date);

CREATE OR REPLACE FUNCTION protect_schedule_assignment_fence()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    operation_id_value UUID;
    operation_source BIGINT;
    operation_target BIGINT;
    operation_date DATE;
    operation_state VARCHAR(16);
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'assignment fences are retained';
    END IF;

    IF NEW.assignment_id IS DISTINCT FROM OLD.assignment_id
       OR NEW.group_id IS DISTINCT FROM OLD.group_id
       OR NEW.subject_id IS DISTINCT FROM OLD.subject_id
       OR NEW.semester_id IS DISTINCT FROM OLD.semester_id
       OR NEW.assigned_teacher_id IS DISTINCT FROM OLD.assigned_teacher_id
       OR NEW.lesson_type IS DISTINCT FROM OLD.lesson_type
       OR NEW.valid_from IS DISTINCT FROM OLD.valid_from THEN
        RAISE EXCEPTION 'assignment fence provenance is immutable';
    END IF;
    IF NEW.revision < OLD.revision THEN
        RAISE EXCEPTION 'assignment fence revision cannot move backwards';
    END IF;

    IF NEW.cap_until_exclusive > OLD.cap_until_exclusive THEN
        RAISE EXCEPTION 'assignment retention cap cannot widen';
    END IF;
    IF NEW.cap_until_exclusive < OLD.cap_until_exclusive THEN
        IF EXISTS (SELECT 1 FROM lessons
                    WHERE assignment_id = OLD.assignment_id AND date >= NEW.cap_until_exclusive)
           OR EXISTS (SELECT 1 FROM lesson_occurrences
                       WHERE assignment_id = OLD.assignment_id
                         AND occurrence_date >= NEW.cap_until_exclusive) THEN
            RAISE EXCEPTION 'assignment retention cap cannot exclude retained rows';
        END IF;
    END IF;

    IF NEW.creation_cap_until_exclusive > OLD.creation_cap_until_exclusive THEN
        RAISE EXCEPTION 'assignment creation cap cannot widen';
    END IF;
    IF NEW.creation_cap_until_exclusive < OLD.creation_cap_until_exclusive THEN
        operation_id_value := NULLIF(current_setting(
            'rutcampustrack.schedule_assignment_rebind_operation_id', true), '')::UUID;
        IF operation_id_value IS NULL THEN
            RAISE EXCEPTION 'assignment creation cap can only narrow during replacement';
        END IF;
        SELECT source_assignment_id, target_assignment_id, effective_from, state
          INTO operation_source, operation_target, operation_date, operation_state
          FROM schedule_assignment_replacement_operations
         WHERE operation_id = operation_id_value
         FOR UPDATE;
        IF NOT FOUND OR operation_source <> OLD.assignment_id
           OR NEW.creation_cap_until_exclusive <> operation_date
           OR operation_state <> 'PREPARED' THEN
            RAISE EXCEPTION 'creation cap change does not match the exact prepared replacement';
        END IF;
    END IF;
    RETURN NEW;
END
$$;

CREATE OR REPLACE FUNCTION protect_schedule_assignment_replacement_operation()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        RAISE EXCEPTION 'replacement operations are retained';
    END IF;
    IF NEW.operation_id IS DISTINCT FROM OLD.operation_id
       OR NEW.payload_hash IS DISTINCT FROM OLD.payload_hash
       OR NEW.source_assignment_id IS DISTINCT FROM OLD.source_assignment_id
       OR NEW.target_assignment_id IS DISTINCT FROM OLD.target_assignment_id
       OR NEW.source_teacher_id IS DISTINCT FROM OLD.source_teacher_id
       OR NEW.target_teacher_id IS DISTINCT FROM OLD.target_teacher_id
       OR NEW.group_id IS DISTINCT FROM OLD.group_id
       OR NEW.subject_id IS DISTINCT FROM OLD.subject_id
       OR NEW.semester_id IS DISTINCT FROM OLD.semester_id
       OR NEW.lesson_type IS DISTINCT FROM OLD.lesson_type
       OR NEW.source_valid_from IS DISTINCT FROM OLD.source_valid_from
       OR NEW.valid_until_exclusive IS DISTINCT FROM OLD.valid_until_exclusive
       OR NEW.effective_from IS DISTINCT FROM OLD.effective_from
       OR NEW.created_at IS DISTINCT FROM OLD.created_at THEN
        RAISE EXCEPTION 'replacement operation identity is immutable';
    END IF;
    IF NOT ((OLD.state = 'PREPARED' AND NEW.state = 'APPLIED')
         OR (OLD.state = 'APPLIED' AND NEW.state = 'COMMITTED')
         OR (OLD.state = NEW.state)) THEN
        RAISE EXCEPTION 'invalid replacement operation transition';
    END IF;
    IF NEW.moved_count < OLD.moved_count OR NEW.skipped_count < OLD.skipped_count THEN
        RAISE EXCEPTION 'replacement operation receipt cannot move backwards';
    END IF;
    RETURN NEW;
END
$$;

