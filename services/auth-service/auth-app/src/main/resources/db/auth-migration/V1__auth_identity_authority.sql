-- No profile, membership, group, subject, assignment, report selector/job/artifact
-- table or cross-database object belongs in auth_db. All referenced IDs are local.
CREATE TABLE auth_identity_operations (
    operation_id UUID PRIMARY KEY,
    command_hash BYTEA NOT NULL CHECK (octet_length(command_hash) = 32),
    canonical_command BYTEA NOT NULL,
    kind VARCHAR(24) NOT NULL CHECK (kind IN
        ('CREATE','ROLE','TRANSFER','HEADMAN_REPLACE','ARCHIVE','RESTORE',
         'ADMIN_ACCESS','TELEGRAM_BINDING','RECONCILE')),
    actor_id BIGINT NOT NULL CHECK (actor_id > 0),
    actor_session_id UUID NOT NULL,
    actor_session_version BIGINT NOT NULL CHECK (actor_session_version > 0),
    actor_roles_version BIGINT NOT NULL CHECK (actor_roles_version > 0),
    phase VARCHAR(24) NOT NULL DEFAULT 'PREPARED_FENCED'
        CHECK (phase IN ('PREPARED_FENCED','COMMITTED','FAILED_SAFE')),
    revision BIGINT NOT NULL DEFAULT 1 CHECK (revision > 0),
    error_code VARCHAR(64),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    finished_at TIMESTAMPTZ,
    CHECK ((phase = 'PREPARED_FENCED') = (finished_at IS NULL)),
    CHECK ((phase = 'FAILED_SAFE') = (error_code IS NOT NULL)),
    CHECK (error_code IS NULL OR error_code ~ '^[A-Z][A-Z0-9_]{0,63}$')
);

CREATE TABLE auth_identities (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    login VARCHAR(32) NOT NULL UNIQUE,
    password_hash VARCHAR(128) NOT NULL,
    initial_password VARCHAR(128),
    password_changed BOOLEAN NOT NULL DEFAULT false,
    generated_password_origin VARCHAR(16) DEFAULT 'initial'
        CHECK (generated_password_origin IS NULL OR generated_password_origin IN ('initial','headman_reset')),
    telegram_id BIGINT UNIQUE CHECK (telegram_id IS NULL OR telegram_id > 0),
    telegram_username VARCHAR(64),
    account_state VARCHAR(16) NOT NULL DEFAULT 'PENDING'
        CHECK (account_state IN ('PENDING','ACTIVE','ARCHIVED')),
    roles_version BIGINT NOT NULL DEFAULT 1 CHECK (roles_version > 0),
    credentials_version BIGINT NOT NULL DEFAULT 1 CHECK (credentials_version > 0),
    telegram_binding_version BIGINT NOT NULL DEFAULT 1 CHECK (telegram_binding_version > 0),
    provision_operation_id UUID NOT NULL REFERENCES auth_identity_operations(operation_id),
    fence_operation_id UUID REFERENCES auth_identity_operations(operation_id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK (account_state <> 'PENDING' OR fence_operation_id IS NOT NULL),
    CHECK (NOT password_changed OR (initial_password IS NULL AND generated_password_origin IS NULL)),
    CHECK (password_hash ~ '^\$2[aby]\$[0-9]{2}\$[./A-Za-z0-9]{53}$')
);

CREATE TABLE user_role_grants (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES auth_identities(id) ON DELETE RESTRICT,
    role VARCHAR(16) NOT NULL CHECK (role IN ('student','headman','teacher','admin')),
    status VARCHAR(16) NOT NULL,
    group_id BIGINT CHECK (group_id IS NULL OR group_id > 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (id,user_id),
    UNIQUE (user_id,role),
    CHECK ((role='student' AND status IN ('active','expelled','graduated','suspended','archived'))
        OR (role='teacher' AND status IN ('active','dismissed','suspended','archived'))
        OR (role='headman' AND status IN ('active','suspended','archived'))
        OR (role='admin' AND status IN ('active','archived'))),
    CHECK (role NOT IN ('student','headman') OR group_id IS NOT NULL),
    CHECK (role IN ('student','headman') OR group_id IS NULL)
);
-- group_id is an opaque admission context, never a second membership authority.
CREATE INDEX auth_grants_group_context ON user_role_grants(group_id,user_id)
    WHERE role IN ('student','headman') AND status='active';

CREATE TABLE admin_access_profiles (
    user_id BIGINT PRIMARY KEY REFERENCES auth_identities(id) ON DELETE RESTRICT,
    assigned BOOLEAN NOT NULL,
    mode VARCHAR(16),
    permissions TEXT[] NOT NULL DEFAULT '{}',
    version BIGINT NOT NULL CHECK (version > 0),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    CHECK ((assigned AND mode IS NOT NULL) OR (NOT assigned AND mode IS NULL)),
    CHECK (((NOT assigned AND mode IS NULL AND cardinality(permissions)=0)
        OR (assigned AND mode='FULL' AND cardinality(permissions)=0)
        OR (assigned AND mode='LIMITED' AND cardinality(permissions)>0
            AND NOT ('ADMIN_ACCESS_MANAGE'=ANY(permissions)))) IS TRUE),
    CHECK (array_position(permissions,NULL) IS NULL)
);

CREATE TABLE auth_identity_operation_targets (
    operation_id UUID NOT NULL REFERENCES auth_identity_operations(operation_id),
    user_id BIGINT NOT NULL REFERENCES auth_identities(id),
    expected_roles_version BIGINT NOT NULL CHECK (expected_roles_version >= 0),
    final_roles_version BIGINT NOT NULL CHECK (final_roles_version > 0),
    expected_credentials_version BIGINT NOT NULL CHECK (expected_credentials_version >= 0),
    prepared_credentials_version BIGINT NOT NULL CHECK (prepared_credentials_version > 0),
    expected_binding_version BIGINT NOT NULL CHECK (expected_binding_version >= 0),
    prepared_binding_version BIGINT NOT NULL CHECK (prepared_binding_version > 0),
    expected_academic_revision BIGINT NOT NULL CHECK (expected_academic_revision >= 0),
    committed_academic_revision BIGINT,
    desired_grants JSONB NOT NULL CHECK (jsonb_typeof(desired_grants)='array'),
    desired_admin_profile JSONB NOT NULL CHECK (jsonb_typeof(desired_admin_profile)='object'),
    desired_account_state VARCHAR(16) NOT NULL CHECK (desired_account_state IN ('ACTIVE','ARCHIVED')),
    supersedes_failed_operation_id UUID REFERENCES auth_identity_operations(operation_id),
    PRIMARY KEY (operation_id,user_id),
    CHECK (final_roles_version=expected_roles_version+1),
    CHECK (committed_academic_revision IS NULL OR committed_academic_revision>expected_academic_revision)
);

