import { afterEach, describe, expect, it, vi } from 'vitest'
import { NotificationInboxHold } from './notification-inbox-gesture'
afterEach(() => { vi.useRealTimers() })
describe('notification readcard hold interaction', () => {
  it('opens menu once and consumes only the post-hold pointer click', () => {
    vi.useFakeTimers()
    const menu = vi.fn()
    const hold = new NotificationInboxHold(menu)
    hold.start(1, 20, 30)
    vi.advanceTimersByTime(550)
    expect(menu).toHaveBeenCalledTimes(1)
    hold.end(1)
    expect(hold.consumeClick(false)).toBe(false)
    expect(hold.consumeClick(true)).toBe(true)
    expect(hold.consumeClick(true)).toBe(false)
  })
  it.each(['move', 'scroll', 'pointercancel', 'release', 'unmount'] as const)('aborts on %s before the deadline', (reason) => {
    vi.useFakeTimers()
    const menu = vi.fn()
    const hold = new NotificationInboxHold(menu)
    hold.start(4, 20, 30)
    vi.advanceTimersByTime(200)
    if (reason === 'move') hold.move(4, 20, 41)
    else if (reason === 'release') hold.end(4)
    else hold.cancel()
    vi.advanceTimersByTime(600)
    expect(menu).not.toHaveBeenCalled()
    expect(hold.consumeClick(true)).toBe(false)
  })
  it('ignores another pointer and allows a new ordinary click after a hold', () => {
    vi.useFakeTimers()
    const menu = vi.fn()
    const hold = new NotificationInboxHold(menu)
    hold.start(1, 10, 10)
    hold.move(2, 100, 100)
    hold.end(2)
    hold.move(1, 13, 14)
    vi.advanceTimersByTime(550)
    expect(menu).toHaveBeenCalledTimes(1)
    hold.end(1)
    hold.start(1, 10, 10)
    hold.end(1)
    expect(hold.consumeClick(true)).toBe(false)
  })
})
