CREATE FUNCTION guard_auth_identity_operation_target() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'identity operation target must be retained';
    END IF;
    IF (to_jsonb(NEW)-'committed_academic_revision')
        IS DISTINCT FROM (to_jsonb(OLD)-'committed_academic_revision')
        OR OLD.committed_academic_revision IS NOT NULL
        OR NEW.committed_academic_revision IS NULL THEN
        RAISE EXCEPTION 'identity target preparation is immutable';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER auth_identity_operation_target_guard BEFORE UPDATE OR DELETE
    ON auth_identity_operation_targets FOR EACH ROW
    EXECUTE FUNCTION guard_auth_identity_operation_target();

CREATE FUNCTION guard_auth_identity_operation() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP='DELETE' THEN
        RAISE EXCEPTION 'identity operation result must be retained';
    END IF;
    IF ROW(NEW.operation_id,NEW.command_hash,NEW.canonical_command,NEW.kind,
           NEW.actor_id,NEW.actor_session_id,NEW.actor_session_version,NEW.actor_roles_version,NEW.created_at)
        IS DISTINCT FROM
       ROW(OLD.operation_id,OLD.command_hash,OLD.canonical_command,OLD.kind,
           OLD.actor_id,OLD.actor_session_id,OLD.actor_session_version,OLD.actor_roles_version,OLD.created_at)
        OR OLD.phase<>'PREPARED_FENCED'
        OR NEW.phase NOT IN ('COMMITTED','FAILED_SAFE')
        OR NEW.revision<>OLD.revision+1 THEN
        RAISE EXCEPTION 'invalid identity operation transition';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER auth_identity_operation_guard BEFORE UPDATE OR DELETE ON auth_identity_operations
    FOR EACH ROW EXECUTE FUNCTION guard_auth_identity_operation();

-- Unlike the historical shared-DB chain there is no per-grant RV trigger.
-- The sole operation writer reserves final RV at PREPARE, persists it in the
-- Academic APPLY receipt, and uses exactly the same RV when clearing the fence.
CREATE FUNCTION guard_auth_identity_versions() RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.id<>OLD.id OR NEW.login<>OLD.login OR NEW.provision_operation_id<>OLD.provision_operation_id
        OR NEW.roles_version<OLD.roles_version OR NEW.roles_version>OLD.roles_version+1 THEN
        RAISE EXCEPTION 'invalid identity generation';
    END IF;
    IF NEW.roles_version<>OLD.roles_version AND NEW.fence_operation_id IS NULL THEN
        RAISE EXCEPTION 'new authority generation requires a prepared fence';
    END IF;
    IF OLD.fence_operation_id IS NOT NULL AND NEW.fence_operation_id IS NULL
        AND NOT EXISTS (SELECT 1 FROM auth_identity_operations o
            JOIN auth_identity_operation_targets t ON t.operation_id=o.operation_id
            WHERE o.operation_id=OLD.fence_operation_id AND o.phase='COMMITTED'
              AND t.user_id=NEW.id AND t.final_roles_version=NEW.roles_version
              AND t.committed_academic_revision IS NOT NULL) THEN
        RAISE EXCEPTION 'fence release requires an exact committed Academic receipt';
    END IF;
    IF OLD.account_state='PENDING' AND NEW.account_state<>'PENDING'
        AND NEW.fence_operation_id IS NOT NULL THEN
        RAISE EXCEPTION 'pending identity activation requires committed fence release';
    END IF;
    IF ROW(NEW.password_hash,NEW.initial_password,NEW.password_changed)
        IS DISTINCT FROM ROW(OLD.password_hash,OLD.initial_password,OLD.password_changed) THEN
        IF NEW.credentials_version<>OLD.credentials_version THEN
            RAISE EXCEPTION 'credential version is tuple maintained';
        END IF;
        NEW.credentials_version:=OLD.credentials_version+1;
    ELSIF NEW.credentials_version<>OLD.credentials_version THEN
        RAISE EXCEPTION 'credential version is tuple maintained';
    END IF;
    IF NEW.telegram_id IS DISTINCT FROM OLD.telegram_id THEN
        IF NEW.telegram_binding_version<>OLD.telegram_binding_version THEN
            RAISE EXCEPTION 'binding version is tuple maintained';
        END IF;
        NEW.telegram_binding_version:=OLD.telegram_binding_version+1;
    ELSIF NEW.telegram_binding_version<>OLD.telegram_binding_version THEN
        RAISE EXCEPTION 'binding version is tuple maintained';
    END IF;
    RETURN NEW;
END $$;
CREATE TRIGGER auth_identity_versions BEFORE UPDATE ON auth_identities
    FOR EACH ROW EXECUTE FUNCTION guard_auth_identity_versions();

CREATE TABLE auth_sessions (
    sid UUID PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES auth_identities(id) ON DELETE RESTRICT,
    active_role_grant_id BIGINT,
    session_version BIGINT NOT NULL CHECK (session_version>0),
    current_refresh_jti UUID NOT NULL UNIQUE,
    previous_refresh_jti UUID,
    refresh_expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL,
    last_seen_at TIMESTAMPTZ NOT NULL,
    revoked_at TIMESTAMPTZ,
    revoke_reason VARCHAR(32),
    auth_method VARCHAR(16) NOT NULL CHECK (auth_method IN ('PASSWORD','OTP','TMA','QR')),
    client_label VARCHAR(160),
    location_label VARCHAR(160),
    UNIQUE(sid,user_id),
    FOREIGN KEY(active_role_grant_id,user_id) REFERENCES user_role_grants(id,user_id),
    CHECK(previous_refresh_jti IS NULL OR previous_refresh_jti<>current_refresh_jti),
    CHECK(refresh_expires_at>created_at AND last_seen_at>=created_at),
    CHECK((revoked_at IS NULL)=(revoke_reason IS NULL)),
    CHECK(revoke_reason IS NULL OR revoke_reason IN
        ('CURRENT_LOGOUT','LOGOUT_ALL','PASSWORD_CHANGED','SECURITY_REVOKED'))
);
CREATE INDEX auth_sessions_live_user ON auth_sessions(user_id,created_at DESC,sid DESC)
    WHERE revoked_at IS NULL;

CREATE TABLE account_security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES auth_identities(id),
    sid UUID,
    event_type VARCHAR(32) NOT NULL CHECK(event_type IN
        ('LOGIN','ROLE_CHANGED','CURRENT_LOGOUT','LOGOUT_ALL','PASSWORD_CHANGED','SECURITY_REVOKED')),
    occurred_at TIMESTAMPTZ NOT NULL,
    auth_method VARCHAR(16) CHECK(auth_method IS NULL OR auth_method IN ('PASSWORD','OTP','TMA','QR')),
    client_label VARCHAR(160),
    location_label VARCHAR(160),
    FOREIGN KEY(sid,user_id) REFERENCES auth_sessions(sid,user_id)
);
CREATE INDEX auth_security_events_user_time ON account_security_events(user_id,occurred_at DESC,id DESC);

CREATE TABLE password_reset_tokens (
    id BIGSERIAL PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES auth_identities(id) ON DELETE RESTRICT,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE auth_outbox (
    id BIGSERIAL PRIMARY KEY,
    event_type VARCHAR(128) NOT NULL,
    payload JSONB NOT NULL,
    status VARCHAR(16) NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','sent','failed')),
    retry_count INTEGER NOT NULL DEFAULT 0,
    last_error TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    sent_at TIMESTAMPTZ
);
CREATE UNIQUE INDEX auth_outbox_event_id ON auth_outbox((payload->>'event_id'));
CREATE INDEX auth_outbox_pending ON auth_outbox(created_at) WHERE status='pending';
CREATE INDEX auth_outbox_sent_cleanup ON auth_outbox(sent_at) WHERE status='sent';

