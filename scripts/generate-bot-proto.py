#!/usr/bin/env python3
"""Generate the Academic bot consumer with the existing pinned Python toolchain."""

import argparse
from importlib.metadata import version
import os
from pathlib import Path
import tempfile

from google.protobuf import descriptor_pb2
from grpc_tools import protoc


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    repository = Path(__file__).resolve().parent.parent
    parser.add_argument("--proto-dir", type=Path, default=repository / "proto")
    parser.add_argument(
        "--output-dir",
        type=Path,
        default=repository / "services/notification-bot/bot/grpc_client",
    )
    args = parser.parse_args()

    for package, expected in (("grpcio-tools", "1.73.0"), ("grpcio", "1.73.0"), ("protobuf", "6.31.0")):
        if version(package) != expected:
            raise RuntimeError(f"Expected {package}=={expected}")

    proto_dir = args.proto_dir.resolve(strict=True)
    source = proto_dir / "academic.proto"
    if not source.is_file() or source.is_symlink():
        raise RuntimeError("Expected a regular academic.proto in the selected proto directory")
    output_dir = args.output_dir.resolve()
    if output_dir == proto_dir:
        raise RuntimeError("Generated outputs must be separate from proto sources")
    output_dir.parent.mkdir(parents=True, exist_ok=True)

    # Stage both files before publishing. Wrong tools/source/import shapes cannot
    # leave a partially adapted generated consumer in the destination directory.
    with tempfile.TemporaryDirectory(prefix=".academic-proto-", dir=output_dir.parent) as temporary:
        staging = Path(temporary)
        result = protoc.main(
            [
                "grpc_tools.protoc",
                f"--proto_path={proto_dir}",
                f"--python_out={staging}",
                f"--grpc_python_out={staging}",
                f"--descriptor_set_out={staging / 'academic.descriptor'}",
                str(source),
            ]
        )
        if result != 0:
            raise RuntimeError("Academic Python protoc generation failed")
        descriptors = descriptor_pb2.FileDescriptorSet.FromString((staging / "academic.descriptor").read_bytes())
        if (
            len(descriptors.file) != 1
            or descriptors.file[0].name != "academic.proto"
            or descriptors.file[0].package != "rutcampustrack.academic"
        ):
            raise RuntimeError("Expected the standard Academic descriptor identity")

        message = staging / "academic_pb2.py"
        service = staging / "academic_pb2_grpc.py"
        message_source = message.read_text(encoding="utf-8")
        service_source = service.read_text(encoding="utf-8")
        if "# source: academic.proto\n" not in message_source:
            raise RuntimeError("Generated descriptor source must remain academic.proto")
        if not service_source.startswith("# Generated by the gRPC Python protocol compiler plugin. DO NOT EDIT!\n"):
            raise RuntimeError("Unexpected Academic gRPC generated header")
        absolute_import = "import academic_pb2 as academic__pb2\n"
        relative_import = "from . import academic_pb2 as academic__pb2\n"
        if service_source.count(absolute_import) != 1 or relative_import in service_source:
            raise RuntimeError("Expected exactly one standard Academic protobuf import to adapt")
        adapted = service_source.replace(absolute_import, relative_import, 1)
        if adapted.replace(relative_import, absolute_import, 1) != service_source:
            raise RuntimeError("Academic relative-import adaptation changed unexpected content")
        service.write_text(adapted, encoding="utf-8")
        output_dir.mkdir(parents=True, exist_ok=True)
        for generated in (message, service):
            destination = output_dir / generated.name
            if destination.is_symlink():
                raise RuntimeError("Generated output destinations must not be symlinks")
        for generated in (message, service):
            os.replace(generated, output_dir / generated.name)


if __name__ == "__main__":
    main()
